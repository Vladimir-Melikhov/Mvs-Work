# Дедупликация, нормализация корней, сортировка по убыванию длины
_NORMALIZED_ROOTS = sorted(
    set(_normalize(r) for r in _FORBIDDEN_ROOTS),
    key=len,
    reverse=True,
)

# Компилируем паттерны (простой поиск подстроки без границ — т.к. текст
# уже слипшийся после нормализации)
_COMPILED: List[re.Pattern] = [
    re.compile(re.escape(root), re.IGNORECASE | re.UNICODE)
    for root in _NORMALIZED_ROOTS
]

# Карта нормализованный-корень → оригинальный (для сообщений об ошибках)
_ROOT_ORIGINAL: Dict[str, str] = {
    _normalize(r): r for r in _FORBIDDEN_ROOTS
}


# ---------------------------------------------------------------------------
# Публичный API
# ---------------------------------------------------------------------------

def find_forbidden(text: str) -> List[str]:
    """
    Ищет запрещённые слова в тексте.

    Возвращает список найденных корней (дедуплицированный, оригинальная форма).
    Пустой список означает, что текст чистый.
    """
    if not text or not isinstance(text, str):
        return []

    norm = _normalize(text)
    found: List[str] = []

    for root_norm, pat in zip(_NORMALIZED_ROOTS, _COMPILED):
        if pat.search(norm):
            # Возвращаем оригинальную форму корня для читаемых сообщений
            original = _ROOT_ORIGINAL.get(root_norm, root_norm)
            found.append(original)

    return list(dict.fromkeys(found))  # убираем дубли, сохраняем порядок


def is_clean(text: str) -> bool:
    """True если текст НЕ содержит запрещённых слов."""
    return len(find_forbidden(text)) == 0


def check_fields(**fields: str) -> Dict[str, List[str]]:
    """
    Проверяет несколько полей сразу.
    Возвращает словарь: имя_поля → список_найденных_корней.
    Поля без нарушений в результат не включаются.

    Пример::

        violations = check_fields(title="Разработка", description="пиздец проект")
        # {'description': ['пиздец', 'пизд']}
    """
    result: Dict[str, List[str]] = {}
    for field_name, value in fields.items():
        if not isinstance(value, str) or not value:
            continue
        hits = find_forbidden(value)
        if hits:
            result[field_name] = hits
    return result